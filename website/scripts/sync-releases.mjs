#!/usr/bin/env node
// Builds src/data/releases.json and public/_redirects from the published
// releases, so the site never hard-codes a version.
//
//   node scripts/sync-releases.mjs
//
// Env:
//   RELEASES_REPO   owner/name to read releases from (default cc-vb/dictator)
//   GITHUB_TOKEN    needed once the repo is private
//   DOWNLOAD_BASE   where the .dmg files are served from. Unset, links point at
//                   GitHub release assets. Set (e.g. https://dl.example.com),
//                   links become DOWNLOAD_BASE/vX.Y.Z/Dictator-X.Y.Z.dmg, which
//                   is the layout the release workflow uploads to.
//
// If the API cannot be reached the existing releases.json is kept, so an
// offline build still works with the last known list.

import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";

const REPO = process.env.RELEASES_REPO || "cc-vb/dictator";
const TOKEN = process.env.GITHUB_TOKEN || "";
const BASE = (process.env.DOWNLOAD_BASE || "").replace(/\/$/, "");

const DATA = fileURLToPath(new URL("../src/data/releases.json", import.meta.url));
const REDIRECTS = fileURLToPath(new URL("../public/_redirects", import.meta.url));

// Every release so far targets the same machines. A release that changes
// this says so in its notes and the value here moves with it.
const MAC = { minOS: "14.0", arch: "Apple silicon" };

async function fetchReleases() {
  const headers = { Accept: "application/vnd.github+json", "User-Agent": "dictator-website" };
  if (TOKEN) headers.Authorization = `Bearer ${TOKEN}`;
  const res = await fetch(`https://api.github.com/repos/${REPO}/releases?per_page=100`, { headers });
  if (!res.ok) throw new Error(`GitHub API ${res.status} ${res.statusText}`);
  return res.json();
}

// Release bodies repeat the install steps and end with the checksum block.
// Keep only what is specific to the version: anything before the install text.
function notesFrom(body = "") {
  const text = body.replace(/```[\s\S]*?```/g, "").trim();
  const first = text.split(/\n\s*\n/)[0] || "";
  return first.replace(/\s+/g, " ").trim();
}

function toEntry(rel) {
  const version = rel.tag_name.replace(/^v/, "");
  const file = `Dictator-${version}.dmg`;
  const asset = rel.assets.find((a) => a.name === file);
  if (!asset) return null;
  const sha256 = (asset.digest || "").replace(/^sha256:/, "");
  const url = BASE ? `${BASE}/v${version}/${file}` : asset.browser_download_url;
  return {
    version,
    date: rel.published_at,
    notes: notesFrom(rel.body),
    mac: { file, url, size: asset.size, sha256, ...MAC },
  };
}

function byVersionDesc(a, b) {
  const pa = a.version.split(".").map(Number);
  const pb = b.version.split(".").map(Number);
  for (let i = 0; i < Math.max(pa.length, pb.length); i++) {
    const d = (pb[i] || 0) - (pa[i] || 0);
    if (d) return d;
  }
  return 0;
}

function redirectsFor(releases) {
  const [latest] = releases;
  const lines = [
    "# Generated by scripts/sync-releases.mjs. Do not edit by hand.",
    `/download/mac          ${latest.mac.url}  302`,
    `/download/mac/latest   ${latest.mac.url}  302`,
    ...releases.map((r) => `/download/mac/${r.version}  ${r.mac.url}  302`),
  ];
  return lines.join("\n") + "\n";
}

async function main() {
  let releases;
  try {
    const raw = await fetchReleases();
    releases = raw
      .filter((r) => !r.draft && !r.prerelease)
      .map(toEntry)
      .filter(Boolean)
      .sort(byVersionDesc);
  } catch (err) {
    const existing = JSON.parse(await readFile(DATA, "utf8").catch(() => "null"));
    if (!existing?.releases?.length) throw err;
    console.warn(`sync-releases: ${err.message}; keeping the existing list`);
    releases = existing.releases;
  }

  if (!releases.length) throw new Error("sync-releases: no release has a Dictator-<version>.dmg");

  const data = { repo: REPO, latest: releases[0].version, releases };
  await writeFile(DATA, JSON.stringify(data, null, 2) + "\n");
  await writeFile(REDIRECTS, redirectsFor(releases));
  console.log(`sync-releases: ${releases.length} releases, latest ${data.latest}`);
}

main().catch((err) => {
  console.error(err.message);
  process.exit(1);
});
